## Pest Agent Browser Plugin

- `vendor/bin/pest --agent-browser="<code>"` runs a one-off Pest assertion without creating a test file — useful for quickly verifying that a change works (a route response, a model relationship, a rendered page, etc.).
- For full usage — backend examples, browser testing, screenshots, combining frontend and backend assertions, RefreshDatabase guidance, and pitfalls — load the **`pest-plugin-agent-browser` skill**.
